// Copies static renderer assets (not compiled by tsc) next to the
// compiled renderer/app.js so relative <link>/<script> paths resolve.
// Also assembles dist/main/preload.cjs from the CommonJS build produced
// by tsconfig.preload.json.
//
// Two Electron preload constraints combine here:
// 1. Electron's preload loader always loads preload scripts via
//    require(), which cannot execute the ESM output that tsconfig.json
//    (module: NodeNext, package "type": "module") produces for the rest
//    of the app — hence the separate CommonJS build. The ".cjs"
//    extension forces Node to treat the file as CommonJS regardless of
//    the package's "type": "module".
// 2. With `sandbox: true` (see main/main.ts), Electron's sandboxed
//    preload loader only resolves require() of Node/Electron built-ins
//    (e.g. "electron") — it cannot resolve relative file requires. So
//    the preload script's small dependency graph
//    (preload.ts -> preload-api.ts -> shared/ipc-channels.ts) is inlined
//    into a single file behind a minimal module registry below.
//
// Run after `tsc -p tsconfig.json && tsc -p tsconfig.preload.json` —
// see package.json "build" script.
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const files = ["renderer/index.html", "renderer/styles.css"];

for (const relPath of files) {
  const src = join(root, relPath);
  const dest = join(root, "dist", relPath);
  await mkdir(dirname(dest), { recursive: true });
  await copyFile(src, dest);
}

await buildPreloadBundle();

async function buildPreloadBundle() {
  const cjsRoot = join(root, "dist", "preload-cjs");

  const ipcChannelsSrc = await readFile(
    join(cjsRoot, "shared", "ipc-channels.js"),
    "utf8",
  );

  const preloadApiSrc = (
    await readFile(join(cjsRoot, "main", "preload-api.js"), "utf8")
  ).replace(
    'require("../shared/ipc-channels.js")',
    '__require("ipc-channels")',
  );

  const preloadSrc = (
    await readFile(join(cjsRoot, "main", "preload.js"), "utf8")
  )
    .replace(
      'require("../shared/ipc-channels.js")',
      '__require("ipc-channels")',
    )
    .replace('require("./preload-api.js")', '__require("preload-api")');

  const bundle = `"use strict";
// Generated by build-copy-static.mjs — do not edit directly.
// See the comment above buildPreloadBundle() in that file for why this
// bundling step exists.
const __registry = {};
const __cache = {};
function __define(id, factory) {
  __registry[id] = factory;
}
function __require(id) {
  if (!(id in __cache)) {
    const module = { exports: {} };
    __cache[id] = module;
    __registry[id](module, module.exports);
  }
  return __cache[id].exports;
}

__define("ipc-channels", function (module, exports) {
${ipcChannelsSrc}
});

__define("preload-api", function (module, exports) {
${preloadApiSrc}
});

${preloadSrc}
`;

  await writeFile(join(root, "dist", "main", "preload.cjs"), bundle, "utf8");
}
